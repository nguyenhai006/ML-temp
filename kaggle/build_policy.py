"""Bundle SetbackPolicy and its PIDPolicy base into one dependency-free file, plus a submission notebook.

Usage (from repo root): uv run python kaggle/build_policy.py
  -> kaggle/setback_standalone.py  (importable locally, for equivalence checks)
  -> kaggle/submission.ipynb       (import on Kaggle: File > Import Notebook)
Re-run whenever pid.py or setback_policy.py changes.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "smart_buildings" / "baselines"
OUT = Path(__file__).resolve().parent / "setback_standalone.py"


def body(path: Path) -> str:
    # Drop the package-internal imports; everything they provide is inlined below.
    return re.sub(r"^from smart_buildings\.[^\n]*\n", "", path.read_text(), flags=re.M)


pid_plus = (BASE / "pid_plus.py").read_text()
constants = "\n".join(
    re.search(rf"^{name} = [^\n]+", pid_plus, re.M).group(0)
    for name in ("MIN_STATIC_PRESSURE_PA", "ECON_K_PER_PA")
)

OUT.write_text(
    "# AUTO-GENERATED by kaggle/build_policy.py from pid.py + setback_policy.py. Do not edit by hand.\n"
    + body(BASE / "pid.py")
    + "\n\n# Constants inlined from pid_plus.py\n" + constants + "\n\n"
    + body(BASE / "setback_policy.py")
)
print(f"wrote {OUT} ({len(OUT.read_text().splitlines())} lines)")

# Server wrapper copied from the official TransferPolicy notebook (ayushrai1114/transferpolicy-notebook).
SERVER = '''

import sys
sys.path.append('/kaggle/input/competitions/neurips-2026-smart-buildings/kaggle_evaluation')
from kaggle_evaluation import smart_buildings_inference_server

COMPETITION_DATA_FOLDER = '/kaggle/input/competitions/neurips-2026-smart-buildings/'


class TransferPolicy(smart_buildings_inference_server.Policy):
    def __init__(self, building_meta_data, action_spec):
        super().__init__(building_meta_data, action_spec)
        self.inner = SetbackPolicy(building_meta_data, action_spec)
        c, d = action_spec['continuous_action'], action_spec['discrete_action']
        self.c_low, self.c_high, self.d_low, self.d_high = c.low, c.high, d.low, d.high

    def get_action(self, obs):
        a = self.inner.get_action(obs)
        # The gateway rejects out-of-range actions, so clip into the spec's own bounds.
        return {
            'continuous_action': np.clip(a['continuous_action'], self.c_low, self.c_high).astype(np.float32),
            'discrete_action': np.clip(a['discrete_action'], self.d_low, self.d_high).astype(np.int32),
        }


smart_buildings_inference_server.SmartBuildingsInferenceServer(TransferPolicy).run(
    competition_data_folder=COMPETITION_DATA_FOLDER,
)
'''

source = OUT.read_text() + SERVER
nb = {
    "cells": [{"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
               "source": source.splitlines(keepends=True)}],
    "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                 "language_info": {"name": "python"}},
    "nbformat": 4, "nbformat_minor": 5,
}
NB = OUT.parent / "submission.ipynb"
NB.write_text(json.dumps(nb, indent=1))
compile(source, str(NB), "exec")  # self-check: the notebook cell is valid Python
print(f"wrote {NB}")
